/**
 * pnpm catalogue:checklist — what a person still needs to enter for the top 20 apps (NEXT-STEPS P1.9):
 * the crawl pages (pricing, integrations, security, terms…) and the UK Companies House number. Writes
 * docs/catalogue-checklist.md. URLs are found by a person on the vendor's own site and written into
 * catalog/apps.yaml (never guessed); then `pnpm crawl` fetches them.
 */
import fs from "node:fs";
import { apps } from "@/lib/catalog/load";

/** The ecommerce / SaaS stack first (v1.1 P): selling channels, SaaS billing + metrics, stock, bills, spend, cash. */
export const TOP_20 = [
  "shopify", "amazon_seller", "a2x", "linkmybooks", "paypal", "stripe", "chargebee", "chartmogul", "baremetrics", "gocardless",
  "chaser", "cin7", "brightpearl", "katana", "unleashed", "dext", "pleo", "spendesk", "float", "syft",
];
const PAGES = ["home", "pricing", "product", "integrations", "security", "terms"] as const;

const byId = new Map(apps().map((a) => [a.id, a]));
const rows = TOP_20.map((id) => {
  const a = byId.get(id);
  if (!a) throw new Error(`Unknown app in TOP_20: ${id}`);
  const crawl = (a.crawl ?? {}) as Record<string, string | null | undefined>;
  const missing = PAGES.filter((p) => !crawl[p]);
  return { a, crawl, missing, ch: a.companies_house ?? null };
});

const todo = rows.reduce((n, r) => n + r.missing.length + (r.ch ? 0 : 1), 0);
const out = [
  "# Catalogue checklist: top 20 apps",
  "",
  `Generated by \`pnpm catalogue:checklist\` on ${new Date().toISOString().slice(0, 10)}. ${todo} things to enter.`,
  "",
  "For each app, find the page on the vendor's **own** site and write its path into `crawl:` in `catalog/apps.yaml`",
  "(e.g. `integrations: /integrations`). Add `companies_house: \"01234567\"` from find-and-update.company-information.service.gov.uk",
  "for UK vendors. Then run `pnpm crawl` (and the monthly cron keeps them fresh). Facts we can't find stay",
  "\"Not published · we're checking\".",
  "",
  "| App | Website | " + PAGES.join(" | ") + " | Companies House |",
  "|---|---|" + PAGES.map(() => "---").join("|") + "|---|",
  ...rows.map(
    (r) =>
      `| ${r.a.name} | ${r.a.website ?? "**needs website**"} | ${PAGES.map((p) => (r.crawl[p] ? `\`${r.crawl[p]}\`` : "**enter**")).join(" | ")} | ${r.ch ?? (r.a.markets.includes("UK") ? "**enter (if UK company)**" : "n/a")} |`,
  ),
  "",
];
fs.mkdirSync("docs", { recursive: true });
fs.writeFileSync("docs/catalogue-checklist.md", out.join("\n"), "utf8");
console.log(`docs/catalogue-checklist.md: ${todo} things to enter for ${rows.length} apps.`);
